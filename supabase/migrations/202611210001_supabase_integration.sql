-- Media objects are public for rendering in public posts/stories. Upload,
-- update and delete are restricted to authenticated users' own user-id folder.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'kudasai-media',
  'kudasai-media',
  true,
  104857600,
  array['image/jpeg','image/png','image/gif','image/webp','image/avif','video/mp4','video/webm','video/quicktime']
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

-- Storage policy predicates bind object names to the authenticated user.
drop policy if exists "kudasai media public read" on storage.objects;
create policy "kudasai media public read"
  on storage.objects for select
  using (bucket_id = 'kudasai-media');

drop policy if exists "kudasai media owner upload" on storage.objects;
create policy "kudasai media owner upload"
  on storage.objects for insert to authenticated
  with check (
    bucket_id = 'kudasai-media'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "kudasai media owner update" on storage.objects;
create policy "kudasai media owner update"
  on storage.objects for update to authenticated
  using (
    bucket_id = 'kudasai-media'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  )
  with check (
    bucket_id = 'kudasai-media'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

drop policy if exists "kudasai media owner delete" on storage.objects;
create policy "kudasai media owner delete"
  on storage.objects for delete to authenticated
  using (
    bucket_id = 'kudasai-media'
    and (storage.foldername(name))[1] = (select auth.uid())::text
  );

-- Keep denormalized counters correct under concurrent likes/comments/reposts.
-- Triggers execute as this narrowly scoped function owner so clients never
-- need UPDATE access to public.posts (which the core schema does not grant).
create or replace function public.kudasai_adjust_post_counter()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_post_id uuid;
  delta integer;
  counter_column text;
begin
  target_post_id := case when tg_op = 'DELETE' then old.post_id else new.post_id end;
  delta := case when tg_op = 'DELETE' then -1 else 1 end;
  counter_column := case tg_table_name
    when 'likes' then 'likes_count'
    when 'comments' then 'comments_count'
    when 'reposts' then 'reposts_count'
    else null
  end;
  if counter_column is not null then
    execute format(
      'update public.posts set %I = greatest(coalesce(%I, 0) + $1, 0) where id = $2',
      counter_column, counter_column
    ) using delta, target_post_id;
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

revoke all on function public.kudasai_adjust_post_counter() from public, anon, authenticated;

drop trigger if exists kudasai_like_post_counter on public.likes;
create trigger kudasai_like_post_counter
  after insert or delete on public.likes
  for each row execute function public.kudasai_adjust_post_counter();

drop trigger if exists kudasai_comment_post_counter on public.comments;
create trigger kudasai_comment_post_counter
  after insert or delete on public.comments
  for each row execute function public.kudasai_adjust_post_counter();

drop trigger if exists kudasai_repost_post_counter on public.reposts;
create trigger kudasai_repost_post_counter
  after insert or delete on public.reposts
  for each row execute function public.kudasai_adjust_post_counter();

-- Follow notifications are generated by the database rather than trusting a
-- client-provided recipient. The existing notifications RLS still controls
-- who can read/update each notification.
create or replace function public.kudasai_notify_follow()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if new.follower_id <> new.following_id then
    insert into public.notifications (user_id, from_user_id, type)
    values (new.following_id, new.follower_id, 'follow');
  end if;
  return new;
end;
$$;

revoke all on function public.kudasai_notify_follow() from public, anon, authenticated;
drop trigger if exists kudasai_follow_notification on public.follows;
create trigger kudasai_follow_notification
  after insert on public.follows
  for each row execute function public.kudasai_notify_follow();

notify pgrst, 'reload schema';
